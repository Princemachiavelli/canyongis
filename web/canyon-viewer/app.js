// Canyon GeoPackage viewer: opens a .gpkg in the browser and shows canyons on a map,
// with their description, rappels, conditions, links and ratings.
(function () {
  "use strict";

  // @ngageoint/geopackage 4.2.10 from jsDelivr. Its dist/ folder holds the SQLite WASM.
  const GEOPACKAGE_BASE = "https://cdn.jsdelivr.net/npm/@ngageoint/geopackage@4.2.10/dist/";
  const TABS = ["Overview", "Description", "Rappels", "Conditions", "Links", "Ratings"];
  const ALLOWED_TAGS = new Set(["P", "H4", "UL", "OL", "LI", "A", "B", "I", "BR"]);

  const state = { db: null, canyons: [], selectedId: null, detail: null, tab: "Overview" };
  const $ = (id) => document.getElementById(id);

  // ---- DOM helpers (text is always set with textContent) -------------------------

  function el(tag, attrs, children) {
    const node = document.createElement(tag);
    for (const [key, value] of Object.entries(attrs || {})) {
      if (value === null || value === undefined) continue;
      if (key === "class") node.className = value;
      else node.setAttribute(key, value);
    }
    for (const child of children || []) {
      node.append(child instanceof Node ? child : document.createTextNode(String(child)));
    }
    return node;
  }

  function setStatus(text) {
    $("status").textContent = text;
  }

  // ---- formatting -----------------------------------------------------------------

  function metres(value) {
    if (value === null || value === undefined) return "";
    return `${Math.round(value)} m (${Math.round(value / 0.3048)} ft)`;
  }

  function hours(value) {
    if (value === null || value === undefined) return "";
    return `${value} h`;
  }

  function kilometres(value) {
    if (value === null || value === undefined) return "";
    return `${value.toFixed(1)} km (${(value / 1.609344).toFixed(1)} mi)`;
  }

  function coded(code, label, note) {
    if (!label && code === null) return "";
    const text = code === null || code === undefined ? label : `${code} - ${label}`;
    return note ? `${text} (${note})` : text;
  }

  // ---- HTML from body_html -----------------------------------------------------
  // body_html is generated by our converter, but sanitize again: only the allowed tags
  // and http(s) links survive, everything else is unwrapped to its text.

  function sanitize(html) {
    const doc = new DOMParser().parseFromString(`<body>${html}</body>`, "text/html");
    const walk = (node) => {
      for (const child of Array.from(node.childNodes)) {
        if (child.nodeType === Node.ELEMENT_NODE) {
          walk(child);
          if (!ALLOWED_TAGS.has(child.tagName)) {
            child.replaceWith(...child.childNodes);
          } else if (child.tagName === "A") {
            const href = child.getAttribute("href") || "";
            for (const attr of Array.from(child.attributes)) child.removeAttribute(attr.name);
            if (/^https?:\/\//i.test(href)) {
              child.setAttribute("href", href);
              child.setAttribute("target", "_blank");
              child.setAttribute("rel", "noopener noreferrer");
            } else {
              child.replaceWith(...child.childNodes);
            }
          } else {
            for (const attr of Array.from(child.attributes)) child.removeAttribute(attr.name);
          }
        }
      }
    };
    walk(doc.body);
    return doc.body.innerHTML;
  }

  // ---- map ------------------------------------------------------------------------

  const map = L.map("map", { preferCanvas: true }).setView([34, -118], 7);
  L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", {
    maxZoom: 18,
    attribution: "&copy; OpenStreetMap contributors",
  }).addTo(map);
  const canyonLayer = L.layerGroup().addTo(map);
  const detailLayer = L.layerGroup().addTo(map);

  function drawCanyons() {
    canyonLayer.clearLayers();
    const bounds = [];
    for (const c of state.canyons) {
      if (c.lat === null || c.lon === null) continue;
      const marker = L.circleMarker([c.lat, c.lon], {
        radius: 6, color: "#2f6f4e", fillColor: "#7fc09a", fillOpacity: 0.9, weight: 1,
      });
      marker.bindTooltip(c.title);
      marker.on("click", () => selectCanyon(c.id));
      marker.addTo(canyonLayer);
      bounds.push([c.lat, c.lon]);
    }
    if (bounds.length) map.fitBounds(bounds, { padding: [24, 24], maxZoom: 12 });
  }

  function drawDetail(detail) {
    detailLayer.clearLayers();
    for (const route of detail.routes) {
      if (!route.line) continue;
      const latlngs = route.line.coordinates.map(([lon, lat]) => [lat, lon]);
      L.polyline(latlngs, { color: "#d33", weight: 4 })
        .bindTooltip(`${route.kind}${route.name ? `: ${route.name}` : ""}`)
        .addTo(detailLayer);
    }
    for (const r of detail.rappels) {
      if (!r.point) continue;
      L.circleMarker([r.point.coordinates[1], r.point.coordinates[0]], {
        radius: 5, color: "#000", fillColor: "#ff0", fillOpacity: 1, weight: 1,
      }).bindTooltip(r.label).addTo(detailLayer);
    }
    for (const w of detail.waypoints) {
      if (!w.point) continue;
      L.circleMarker([w.point.coordinates[1], w.point.coordinates[0]], {
        radius: 4, color: "#237", fillColor: "#8ac", fillOpacity: 1, weight: 1,
      }).bindTooltip(`${w.kind}: ${w.name}`).addTo(detailLayer);
    }
  }

  // ---- sidebar --------------------------------------------------------------------

  function renderList() {
    const list = $("canyons");
    list.replaceChildren();
    const filter = $("search").value.trim().toLowerCase();
    for (const c of state.canyons) {
      const haystack = `${c.title} ${c.region || ""}`.toLowerCase();
      if (filter && !haystack.includes(filter)) continue;
      const meta = [c.region, c.technicalRating !== null ? `T${c.technicalRating}` : null,
                    c.waterRating, c.timeRating].filter(Boolean).join(" · ");
      const item = el("li", {
        class: c.id === state.selectedId ? "active" : null,
        "data-id": c.id,
      }, [el("div", {}, [c.title]), el("div", { class: "meta" }, [meta])]);
      item.addEventListener("click", () => selectCanyon(c.id));
      list.append(item);
    }
  }

  // ---- detail tabs ----------------------------------------------------------------

  function renderTabs() {
    const bar = $("tabs");
    bar.replaceChildren();
    for (const name of TABS) {
      const button = el("button", { class: name === state.tab ? "active" : null }, [name]);
      button.addEventListener("click", () => {
        state.tab = name;
        renderTabs();
        renderPanel();
      });
      bar.append(button);
    }
  }

  function table(rows) {
    const body = el("tbody", {}, rows.filter(([, v]) => v !== "" && v !== null && v !== undefined)
      .map(([k, v]) => el("tr", {}, [el("th", {}, [k]), el("td", {}, [String(v)])])));
    return el("table", {}, [body]);
  }

  function renderOverview(d) {
    const c = d.canyon;
    return [
      el("h2", {}, [c.title]),
      c.aka ? el("p", { class: "muted" }, [`Also: ${c.aka}`]) : null,
      table([
        ["Region", c.region],
        ["Technical rating", c.technicalRating],
        ["Water rating", c.waterRating],
        ["Time rating", c.timeRating],
        ["Rappels", c.numberOfRappels],
        ["Longest rappel", metres(c.longestRappelM)],
        ["Hike length", kilometres(c.hikeLengthKm)],
        ["Approach gain", metres(c.approachGainM)],
        ["Exit gain", metres(c.exitGainM)],
        ["Typical time (fastest / slowest)",
          [hours(c.fastestTimeH), hours(c.slowestTimeH)].filter(Boolean).join(" / ")],
        ["Permits", c.permits],
        ["Best season", c.bestSeason],
        ["Vehicle", c.vehicle],
        ["Shuttle (min)", c.shuttle],
        ["Explored", c.explored === null ? null : c.explored ? "Yes" : "No"],
        ["Location", c.point ? `${c.point.coordinates[1]}, ${c.point.coordinates[0]}` : null],
        ["Source", c.sourceUrl ? el("a", { href: c.sourceUrl, target: "_blank", rel: "noopener" },
          ["Ropewiki page"]) : null],
        ["Fetched", c.fetchedAt],
      ]),
    ];
  }

  function renderDescription(d) {
    if (!d.sections.length) return [el("p", { class: "muted" }, ["No description."])];
    return d.sections.map((s) => {
      const body = el("div", {});
      body.innerHTML = sanitize(s.body_html);
      return el("section", {}, [el("h3", {}, [s.heading]), body]);
    });
  }

  function renderRappels(d) {
    if (!d.rappels.length) return [el("p", { class: "muted" }, ["No rappels recorded."])];
    return [el("table", {}, [el("tbody", {}, d.rappels.map((r) => el("tr", {}, [
      el("th", {}, [r.label]),
      el("td", {}, [[metres(r.height_m), r.notes].filter(Boolean).join(" — ")]),
    ])))])];
  }

  function renderConditions(d) {
    if (!d.conditions.length) return [el("p", { class: "muted" }, ["No condition reports."])];
    return d.conditions.map((c) => {
      const dateBadge = c.trip_date_source === "filed_date"
        ? el("span", { class: "badge" }, ["filed date"]) : null;
      const details = table([
        ["Quality", coded(c.quality_code, c.quality_label)],
        ["Water", coded(c.water_code, c.water_label, c.water_note)],
        ["Wetsuit", coded(c.wetsuit_code, c.wetsuit_label, c.wetsuit_note)],
        ["Difficulty", coded(c.difficulty_code, c.difficulty_label, c.difficulty_note)],
        ["Team", [c.team_size ? `${c.team_size} people` : null,
                  c.team_time_h ? `${c.team_time_h} h` : null].filter(Boolean).join(", ")],
        ["Experience", [c.team_min_experience, c.team_max_experience].filter(Boolean).join(" to ")],
        ["Reported by", c.reported_by],
      ]);
      const notes = c.general_notes ? el("p", {}, [c.general_notes]) : null;
      const rappelNotes = c.rappelNotes.length ? el("ul", {}, c.rappelNotes.map((n) =>
        el("li", {}, [el("b", {}, [n.rappel_label]), `: ${n.note}`]))) : null;
      const photos = c.photos.length ? el("p", { class: "muted" }, [
        `Photos: ${c.photos.join(", ")}`]) : null;
      return el("article", { class: "condition" }, [
        el("div", { class: "date" }, [c.trip_date || "No date", dateBadge]),
        details, notes, rappelNotes, photos,
      ]);
    });
  }

  function renderLinks(d) {
    if (!d.links.length) return [el("p", { class: "muted" }, ["No links."])];
    return [el("ul", {}, d.links.map((l) => el("li", {}, [
      el("a", { href: l.url, target: "_blank", rel: "noopener noreferrer" }, [l.label || l.url]),
      l.source_name ? el("span", { class: "muted" }, [` (${l.source_name})`]) : null,
    ])))];
  }

  function renderRatings(d) {
    if (!d.ratings.length) return [el("p", { class: "muted" }, ["No ratings."])];
    const avg = d.ratings.reduce((sum, r) => sum + (r.rating || 0), 0) / d.ratings.length;
    return [
      el("p", {}, [`${d.ratings.length} ratings, average ${avg.toFixed(1)}`]),
      table(d.ratings.map((r) => [r.rater || "anonymous", r.rating])),
    ];
  }

  const RENDERERS = {
    Overview: renderOverview,
    Description: renderDescription,
    Rappels: renderRappels,
    Conditions: renderConditions,
    Links: renderLinks,
    Ratings: renderRatings,
  };

  function renderPanel() {
    const panel = $("panel");
    if (!state.detail) {
      panel.replaceChildren(el("p", { class: "muted" }, ["Select a canyon."]));
      return;
    }
    panel.replaceChildren(...RENDERERS[state.tab](state.detail));
  }

  // ---- actions --------------------------------------------------------------------

  function selectCanyon(id) {
    state.selectedId = id;
    try {
      state.detail = gpkg.loadCanyon(state.db, id);
    } catch (err) {
      console.error(err);
      state.detail = null;
      setStatus(`Could not load canyon ${id}: ${err.message}`);
      $("panel").replaceChildren(el("p", { class: "muted" }, [`Could not load canyon: ${err.message}`]));
      return;
    }
    renderList();
    renderTabs();
    renderPanel();
    if (state.detail) drawDetail(state.detail);
  }

  function loadDatabase(bytes, label) {
    return gpkg.openDatabase(GeoPackage, bytes).then((db) => {
      if (state.db) state.db.close();
      state.db = db;
      state.canyons = gpkg.listCanyons(db);
      state.selectedId = null;
      state.detail = null;
      $("search").disabled = false;
      setStatus(`${label}: ${state.canyons.length} canyons`);
      renderList();
      drawCanyons();
      detailLayer.clearLayers();
      renderTabs();
      renderPanel();
    }).catch((err) => {
      setStatus(`Could not open ${label}: ${err.message}`);
    });
  }

  // A GeoPackage is a SQLite file, so check the header rather than the file name or type.
  const SQLITE_HEADER = "SQLite format 3\0";

  function isSqlite(bytes) {
    if (bytes.length < SQLITE_HEADER.length) return false;
    return SQLITE_HEADER.split("").every((ch, i) => bytes[i] === ch.charCodeAt(0));
  }

  function openFile(file) {
    setStatus(`Reading ${file.name}…`);
    return file.arrayBuffer().then((buf) => {
      const bytes = new Uint8Array(buf);
      if (!isSqlite(bytes)) {
        setStatus(`${file.name} is not a GeoPackage (not a SQLite file)`);
        return null;
      }
      return loadDatabase(bytes, file.name);
    });
  }

  // ---- wiring ---------------------------------------------------------------------

  GeoPackage.setSqljsWasmLocateFile((name) => GEOPACKAGE_BASE + name);

  $("file").addEventListener("change", (event) => {
    const [file] = event.target.files;
    if (file) openFile(file);
  });
  $("search").addEventListener("input", renderList);

  const drop = $("drop");
  ["dragenter", "dragover"].forEach((type) =>
    drop.addEventListener(type, (e) => { e.preventDefault(); drop.classList.add("drop-active"); }));
  ["dragleave", "drop"].forEach((type) =>
    drop.addEventListener(type, (e) => { e.preventDefault(); drop.classList.remove("drop-active"); }));
  drop.addEventListener("drop", (e) => {
    const [file] = e.dataTransfer.files;
    if (file) openFile(file);
  });

  // Optional: ?gpkg=relative/or/absolute/url.gpkg loads a file that is served with the site.
  const url = new URLSearchParams(location.search).get("gpkg");
  if (url) {
    setStatus(`Loading ${url}…`);
    fetch(url)
      .then((r) => { if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.arrayBuffer(); })
      .then((buf) => loadDatabase(new Uint8Array(buf), url))
      .catch((err) => setStatus(`Could not load ${url}: ${err.message}`));
  }

  renderTabs();
  renderPanel();
})();
